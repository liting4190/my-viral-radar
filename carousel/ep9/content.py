def plain(b):
    k=b[0]
    if k in("para","call"): return b[1]
    if k=="sec": return "".join(t for _,t in b[2])
    if k=="list": return "".join(t for _,t in b[1])
    if k=="btn": return b[1]
    return ""
def count(blocks):
    return len(re.sub(r"【/?黄】|\s","","".join(plain(b) for b in blocks)))
